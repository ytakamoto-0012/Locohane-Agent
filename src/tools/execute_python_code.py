"""execute_python_code ツール。"""

from __future__ import annotations

from langchain_core.tools import tool
from pathlib import Path
import asyncio
import chainlit as cl
import logging
import subprocess
import tempfile

from . import _state
from ._duplicate_guard import _track_failure_streak
from ._python_fs_guard import _exec_guard_roots, _python_fs_guard_preamble, _register_exec_output_files
from ._subprocess_env import _subprocess_env
from ._workdir import _resolve_exec_workdir, _tmp_dir_parents

logger = logging.getLogger(__name__)


@tool
async def execute_python_code(code: str) -> str:
    """Run Python code generated by the LLM on the spot and return its stdout/stderr.

    While run_script can only run existing files under skills/*/scripts/, this tool writes the
    code string to a temporary file and runs it on the spot. Running arbitrary code is risky, so
    if it is disabled in the server settings it returns an error without running. As a write
    tool, it cannot run unless a plan has been approved with create_plan/approve_plan (it returns
    an error if not approved).

    **The cwd (working directory) differs from run_script**. The cwd of run_script is the working
    directory set by the user, but the cwd of this tool is always this session's own temporary
    folder under default_workdir (`_tmp_<created time>_<short ID>`), whatever the user's working
    directory is. Files this code writes with relative paths (intermediate artifacts) collect
    there, so the LLM does not clutter the user's working directory directly. You do not need to
    target the user's working directory; simply write with relative paths
    (e.g. `open("ops.json", "w", ...)`). Created/updated files are detected automatically after
    the run, registered in path_memory (`@N`) and included in the return value (you can pass the
    `@N` or the absolute path returned by this tool as is to a later run_script, etc.; run_script
    can also read this temporary folder, so the different cwd is not a problem). The timeout and
    the Python executable reuse the same settings as run_script.

    **Important: using path memory (@N)**
    To use file paths obtained with Glob or other tools (@0, @1, @2...) in the code argument of
    this tool, call `path_memory.resolve()` inside the code to expand them to real paths. The
    `src/` directory is available through the environment variable `AGENT_SRC_DIR`, so you can
    import and expand them like this:

      import os, sys
      sys.path.insert(0, os.environ.get("AGENT_SRC_DIR", ""))
      import path_memory
      thread_id = os.environ.get("AGENT_THREAD_ID", "_no_session")
      pm_dir = os.environ.get("AGENT_PATH_MEMORY_DIR", "")
      if pm_dir:
          resolved = path_memory.resolve(thread_id, "@0", Path(pm_dir))
          print(open(resolved).read()[:500])

    There is never any need to copy a file list into the code as a literal list.

    **Important: limit on the number of files**
    Listing file names as literals in the code argument causes a token explosion (bloated
    conversation history) **beyond 30 files**. With more than 30 files, do not list them in the
    code; walk the directory with glob or pathlib, or prefer calling an existing script with
    run_script.

    **Important: the delegation principle**
    Delegate file investigation, comparison, aggregation, etc. to existing skills or scripts
    implemented for run_script whenever possible. Limit execute_python_code to simple script
    runs and prototyping, and avoid complex data processing or large-scale file operations.

    **Important: writes are limited to the working directory (sandbox)**
    A pre-execution guard automatically blocks any write, delete or rename outside the working
    directory and this session's own temporary folder (`_tmp_<created time>_<short ID>`, which is
    the cwd of this code) (it fails with PermissionError. You cannot write anywhere else at all,
    including the Locohane project folder [src/, app.py, config.ini, skills/, etc.], any other
    drive or folder, and places directly under default_workdir other than
    `_tmp_<created time>_<short ID>` (a shared folder on the server, visible to other sessions)).
    If the project's own settings or source code need to change, do not use this tool; ask the
    user to edit them directly.
    Reading is not covered by this guard and is unrestricted as before.

    Args:
        code: The full Python code to run. If it contains path_memory @N tokens
            (e.g. @0, @1), call `path_memory.resolve()` in the code to expand them to real paths
            (see "using path memory" above).

    Returns:
        A string with "[exit code] N" followed by stdout, stderr and the path_memory references
        of created/updated files (if any), each with a heading. If code is empty, execution is
        disabled, the plan is not approved, it timed out, or starting it failed, it returns an
        "Error: ..." string instead of raising.
    """
    if not code.strip():
        return "Error: code is empty."
    if not _state._CODE_EXEC_ENABLED:
        return "Error: running Python code generated by the LLM is disabled in config.ini " "([scripts] code_execution_enabled=false)."
    workdir = _resolve_exec_workdir()

    if not cl.user_session.get("plan_approved"):
        logger.info("execute_python_code: blocked because the plan is not approved")
        return (
            "Error: cannot run because the plan is not approved. "
            "Create a plan with create_plan, get the user's approval with approve_plan, "
            "and then run it. If your tools do not include create_plan/approve_plan "
            "(you are a sub-agent), do not try again; report this error "
            "as is to the delegator as your final answer."
        )

    try:
        before_snapshot = {p: p.stat().st_mtime for p in workdir.iterdir() if p.is_file()}
    except OSError:
        before_snapshot = {}

    try:
        _guard_allowed_roots, _guard_display_roots = _exec_guard_roots()
        _fs_guard = _python_fs_guard_preamble(
            _guard_allowed_roots, tmp_dir_roots=_tmp_dir_parents(workdir.parent), display_roots=_guard_display_roots
        )
        tmp = tempfile.NamedTemporaryFile(mode="w", suffix=".py", dir=str(workdir), delete=False, encoding="utf-8")
        tmp.write(_fs_guard + code)
        tmp.close()
        tmp_path = Path(tmp.name)
    except OSError as e:
        return f"Error: could not create a temporary file: {e}"

    logger.info("execute_python_code: cwd=%s", workdir)
    try:
        try:
            proc = await asyncio.to_thread(
                subprocess.run,
                [_state._SCRIPT_PYTHON, str(tmp_path)],
                cwd=str(workdir),
                capture_output=True,
                text=True,
                timeout=_state._SCRIPT_TIMEOUT,
                encoding="utf-8",
                errors="replace",
                env=_subprocess_env(),
            )
        except subprocess.TimeoutExpired:
            return f"Error: the code timed out after {_state._SCRIPT_TIMEOUT} seconds."
        except OSError as e:
            return f"Error: could not run the code: {e}"
    finally:
        tmp_path.unlink(missing_ok=True)

    parts = [f"[exit code] {proc.returncode}"]
    if proc.stdout:
        parts.append(f"[stdout]\n{proc.stdout.rstrip()}")
    if proc.stderr:
        parts.append(f"[stderr]\n{proc.stderr.rstrip()}")

    path_memory_note = _register_exec_output_files(workdir, before_snapshot, cl.user_session.get("thread_id") or "_no_session")
    if path_memory_note:
        parts.append(path_memory_note)

    warning = _track_failure_streak("execute_python_code_failure_streak", proc.returncode != 0, "execute_python_code")
    if warning:
        parts.append(warning)
    return "\n".join(parts)
