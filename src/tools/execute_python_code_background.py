"""execute_python_code_background ツール。"""

from __future__ import annotations

from langchain_core.tools import tool
from pathlib import Path
import asyncio
import chainlit as cl
import logging
import tempfile
import time
import uuid

from . import _script_job
from . import _state
from ._python_fs_guard import _exec_guard_roots, _python_fs_guard_preamble
from ._script_job import _BackgroundJob, _background_job_started_message, _finalize_script_job_result, _purge_stale_background_jobs, _run_background_job
from ._subprocess_env import _subprocess_env
from ._workdir import _resolve_exec_workdir, _tmp_dir_parents

logger = logging.getLogger(__name__)


@tool
async def execute_python_code_background(code: str) -> str:
    """Run Python code generated by the LLM in the background.

    For code that is expected to take a long time. Unlike execute_python_code, this turn itself
    blocks until completion (unless the safety limit below is reached) (the Chainlit UI keeps
    showing "running"). While waiting, progress (elapsed seconds, the tail of stdout/stderr) is
    automatically posted to the chat for humans, so you do not need to poll by calling
    check_script_job repeatedly (the code posts progress to the chat directly, so the number of
    LLM calls and token usage do not increase). One call returns the final result in the same
    form as execute_python_code (handled by the same registry and tools as run_script_background
    jobs).

    Only if it still has not finished after the configured safety limit
    ([scripts].background_inline_wait_max_seconds), it returns a notice including the job_id and
    ends this turn (the job itself keeps running in the background). Only in that case, use
    check_script_job (to get the result) and stop_script_job (only when explicitly told to
    interrupt) in later turns.

    Argument checks, working directory resolution, the plan approval check (no exemption; approval
    by create_plan/approve_plan is always required) and the enablement check are the same as
    execute_python_code. Created/updated files are detected automatically on completion,
    registered in path_memory (`@N`) and included in the result.
    The limit before a background job is forcibly stopped is 3600 seconds by default.

    **Important: using path memory (@N)**
    To use file paths obtained with Glob or other tools (@0, @1, @2...) in the code argument of
    this tool, call `path_memory.resolve()` inside the code to expand them to real paths. The
    `src/` directory is available through the environment variable `AGENT_SRC_DIR`, so you can
    import and expand them like this:

      import os, sys
      sys.path.insert(0, os.environ.get("AGENT_SRC_DIR", ""))
      import path_memory
      thread_id = os.environ.get("AGENT_THREAD_ID", "_no_session")
      pm_dir = os.environ.get("AGENT_PATH_MEMORY_DIR", "")
      if pm_dir:
          resolved = path_memory.resolve(thread_id, "@0", Path(pm_dir))
          print(open(resolved).read()[:500])

    There is never any need to copy a file list into the code as a literal list.

    **Important: limit on the number of files**
    Listing file names as literals in the code argument causes a token explosion (bloated
    conversation history) **beyond 30 files**. With more than 30 files, do not list them in the
    code; walk the directory with glob or pathlib, or prefer calling an existing script with
    run_script.

    **Important: the delegation principle**
    Delegate file investigation, comparison, aggregation, etc. to existing skills or scripts
    implemented for run_script whenever possible. Limit execute_python_code to simple script
    runs and prototyping, and avoid complex data processing or large-scale file operations.

    **Important: writes are limited to the working directory (sandbox)**
    A pre-execution guard automatically blocks any write, delete or rename outside the working
    directory and this session's own temporary folder (`_tmp_<created time>_<short ID>`, which is
    the cwd of this code) (it fails with PermissionError. You cannot write anywhere else at all,
    including the Locohane project folder [src/, app.py, config.ini, skills/, etc.], any other
    drive or folder, and places directly under default_workdir other than
    `_tmp_<created time>_<short ID>` (a shared folder on the server, visible to other sessions)).
    If the project's own settings or source code need to change, do not use this tool; ask the
    user to edit them directly.
    Reading is not covered by this guard and is unrestricted as before.

    Args:
        code: The full Python code to run.

    Returns:
        Normally the final result string in the same form as execute_python_code. Only when the
        safety limit is reached, a notice string including the job_id. If code is empty, execution
        is disabled, the plan is not approved, or creating the temporary file or starting it
        failed, it returns an "Error: ..." string like execute_python_code (no job is created in
        that case).
    """
    if not code.strip():
        return "Error: code is empty."
    if not _state._CODE_EXEC_ENABLED:
        return "Error: running Python code generated by the LLM is disabled in config.ini " "([scripts] code_execution_enabled=false)."
    workdir = _resolve_exec_workdir()

    if not cl.user_session.get("plan_approved"):
        logger.info("execute_python_code_background: blocked because the plan is not approved")
        return (
            "Error: cannot run because the plan is not approved. "
            "Create a plan with create_plan, get the user's approval with approve_plan, "
            "and then run it. If your tools do not include create_plan/approve_plan "
            "(you are a sub-agent), do not try again; report this error "
            "as is to the delegator as your final answer."
        )

    try:
        before_snapshot = {p: p.stat().st_mtime for p in workdir.iterdir() if p.is_file()}
    except OSError:
        before_snapshot = {}

    try:
        _guard_allowed_roots, _guard_display_roots = _exec_guard_roots()
        _fs_guard = _python_fs_guard_preamble(
            _guard_allowed_roots, tmp_dir_roots=_tmp_dir_parents(workdir.parent), display_roots=_guard_display_roots
        )
        tmp = tempfile.NamedTemporaryFile(mode="w", suffix=".py", dir=str(workdir), delete=False, encoding="utf-8")
        tmp.write(_fs_guard + code)
        tmp.close()
        tmp_path = Path(tmp.name)
    except OSError as e:
        return f"Error: could not create a temporary file: {e}"

    _purge_stale_background_jobs()

    logger.info("execute_python_code_background: cwd=%s", workdir)
    try:
        process = await asyncio.create_subprocess_exec(
            _state._SCRIPT_PYTHON,
            str(tmp_path),
            cwd=str(workdir),
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            env=_subprocess_env(),
        )
    except OSError as e:
        tmp_path.unlink(missing_ok=True)
        return f"Error: could not start the code: {e}"

    job_id = uuid.uuid4().hex[:12]
    job = _BackgroundJob(
        process=process,
        thread_id=cl.user_session.get("thread_id") or "",
        skill_name="",
        script_filename=tmp_path.name,
        started_at=time.monotonic(),
        stdout_chunks=[],
        stderr_chunks=[],
        status="running",
        returncode=None,
        error_message=None,
        tmp_path=tmp_path,
        workdir=workdir,
        before_snapshot=before_snapshot,
    )
    job.runner_task = asyncio.create_task(_run_background_job(job, job_id))
    _script_job._BACKGROUND_JOBS[job_id] = job

    wait_timeout = _state._SCRIPT_BACKGROUND_INLINE_WAIT_MAX_SECONDS if _state._SCRIPT_BACKGROUND_INLINE_WAIT_MAX_SECONDS > 0 else None
    try:
        await asyncio.wait_for(asyncio.shield(job.runner_task), timeout=wait_timeout)
    except asyncio.TimeoutError:
        logger.warning(
            "execute_python_code_background: reached the safety limit (%s seconds), returning job_id and ending the turn: job_id=%s",
            wait_timeout,
            job_id,
        )
        return _background_job_started_message(job_id)

    return _finalize_script_job_result(job, job_id)
