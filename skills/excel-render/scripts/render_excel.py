"""Excelファイルを画像(PNG)としてレンダリングする。

excel-render スキルの実行スクリプト（progressive disclosure 第3段階）。
run_script ツールから
    python render_excel.py <excel_path>
の形で呼ばれる。全シート（PDF化後の全ページ）を画像化する。

動作概要:
  1. OLE（COM）で Excel をヘッドレス起動し、各シートの印刷設定を横1ページ×
     縦1ページに収まるフィット印刷へ強制した上でファイルをPDFへエクスポート
     （--print-as-is指定時はこの強制を行わず、シートに既に
     設定されている印刷範囲・フィット設定をそのまま使う）。
  2. pypdfium2 で PDF ページを画像化（既定300DPI）。
  3. 白黒境界判定で余白を除去（既定）。
  4. シートの縮尺に応じてキャプチャDPIを動的にブースト
     （--print-as-is指定時はブーストを行わない）。

生成したPNGは、default_workdir配下のセッション専用一時フォルダ
`_tmp_<thread_id>/rendered/` に保存する（run_script の cwd＝ユーザー指定
work_dir ではなく、常に default_workdir 基準。work_dir は保持日数ベースの
自動削除の対象外のため）。
analyze_image は絶対パスをそのまま読めるため、出力JSONの image_path
（絶対パス）を analyze_image に渡せばLLMへ画像として見せられる。
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import traceback
from pathlib import Path

# office_shared/excel_common.py から共有ヘルパーを import する（1-B 相互import方式）
_OFFICE_SHARED = Path(__file__).resolve().parent.parent.parent / "office_shared"
if str(_OFFICE_SHARED) not in sys.path:
    sys.path.append(str(_OFFICE_SHARED))
from excel_common import register_output_path, setup_utf8_stdio  # noqa: E402
from _render import _TARGET_DPI, render_office_file  # noqa: E402

# --print-as-is指定時のターゲットDPI（縮尺ブーストは働かない）。
# 現在は既定の_TARGET_DPIと同値。
_PRINT_AS_IS_TARGET_DPI = 150


def main() -> int:
    setup_utf8_stdio()
    parser = argparse.ArgumentParser()
    parser.add_argument("excel_path")
    parser.add_argument(
        "--print-as-is",
        action="store_true",
        help="convert to PDF using the print area and fit settings already set on the sheet (the default forces fitting to 1 page wide x 1 page tall)",
    )
    args = parser.parse_args()

    path = Path(args.excel_path)
    if not path.exists():
        print(f"File not found: {args.excel_path}", file=sys.stderr)
        return 1
    if path.is_dir():
        print(f"The specified path is a directory (files only): {args.excel_path}", file=sys.stderr)
        return 1
    if path.suffix.lower() not in (".xlsx", ".xlsm", ".xls"):
        print(f"Only the .xlsx/.xlsm/.xls extensions are supported: {path.suffix}", file=sys.stderr)
        return 1

    try:
        result = render_office_file(
            path=path,
            tool="excel",
            force_fit_to_page=not args.print_as_is,
            target_dpi=_PRINT_AS_IS_TARGET_DPI if args.print_as_is else _TARGET_DPI,
        )
    except ImportError as e:
        print(f"A required library was not found (pywin32 is required): {e}", file=sys.stderr)
        return 1
    except Exception as e:
        print(f"Rendering with Excel failed: {e}\n{traceback.format_exc()}", file=sys.stderr)
        return 1

    # パスメモリーへ登録
    path_memory: dict[str, str] = {}
    for image in result.get("images", []):
        pm = register_output_path(image["image_path"], description=f"image of page {image['page']} generated by render_excel")
        if pm:
            path_memory.update(pm)

    if path_memory:
        result["path_memory"] = path_memory

    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
